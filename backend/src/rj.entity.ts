import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  JoinColumn,
  RelationId,
} from 'typeorm';
import { Station } from './station.entity';
import { Listener } from './listener.entity';

@Entity('rjs')
export class Rj {
  @ManyToOne(() => Listener, {
    nullable: true,
    onDelete: 'SET NULL',
  })
  @JoinColumn({ name: 'ownerListenerId' })
  ownerListener: Listener | null;

  @RelationId((rj: Rj) => rj.ownerListener)
  ownerListenerId: string | null;

  @Column({ type: 'varchar', length: 20, default: 'pending' })
  verificationStatus: string;

  /** Code in this RJ's referral link, /r/<code>. Generated by the database. */
  @Column({ type: 'varchar', length: 16, unique: true, insert: false, update: false })
  referralCode: string;

  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ type: 'varchar', length: 100 })
  name: string;

  @Column({ type: 'varchar', length: 100, unique: true })
  slug: string;

  @Column({ type: 'varchar', length: 150, nullable: true })
  email: string | null;

  @Column({ type: 'varchar', length: 20, nullable: true })
  phone: string | null;

  @Column({ type: 'varchar', length: 255, nullable: true })
  photoUrl: string | null;

  @Column({ type: 'boolean', default: true })
  isActive: boolean;

  @ManyToOne(() => Station, { nullable: true, onDelete: 'SET NULL' })
  @JoinColumn({ name: 'stationId' })
  station: Station | null;

  @Column({ type: 'uuid', nullable: true })
  stationId: string | null;

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}